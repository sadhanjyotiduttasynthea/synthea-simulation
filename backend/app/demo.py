"""One-click demonstration of the knowledge → simulation pipeline.

Uses ONLY the clearly-labelled synthetic test document: imports it, runs the local extractor,
approves selected candidates (as a reviewer would), creates digital twins that use the approved
models, and computes their studies. No experimental measurements are fabricated; the
experimental-comparison step is left to the user.
"""
from __future__ import annotations

from . import db, extraction, papers, sample_docs, twins
from .routes_science import approve

NOTE = "Demonstration built from the SYNTHETIC test document (values invented for software testing)."


def _paper() -> dict:
    for p in db.list_docs("papers"):
        if p.get("synthetic_test_document"):
            return p
    p = papers.import_pdf(sample_docs.build_sample_pdf(), "synthetic_test_document_pea_protein.pdf", ["lib-plant-protein", "lib-rheology"])
    p = db.get_doc("papers", p["id"])
    p["synthetic_test_document"] = True
    p["metadata"]["note"] = "SYNTHETIC TEST DOCUMENT generated by Synthea Simulation; values are invented for software testing."
    return db.put_doc("papers", p)


def build(project_id: str = "demo-pea-snack") -> dict:
    log = []
    paper = _paper()
    if not any(e for e in db.list_children("extractions", paper["id"])):
        r = extraction.run(paper["id"])
        log.append(f"extraction: {r['summary']}")
    cands = db.list_children("extractions", paper["id"])
    mat = "mat-pea-protein-isolate"
    approved = []
    wanted_props = {("viscosity", 2.4), ("viscosity", 1.3), ("denaturation_temperature", 84.6), ("thermal_conductivity", 0.52), ("water_holding_capacity", 3.1)}
    for c in cands:
        if c.get("status") != "pending":
            continue
        if c["kind"] == "property" and (c["property"], c.get("value")) in wanted_props:
            approve(c["id"], {"material_id": mat, "review_status": "approved"})
            approved.append(f"{c['property']} {c['value']}")
        elif c["kind"] == "property" and c.get("table_id"):
            approve(c["id"], {"material_id": mat, "review_status": "approved"})
            approved.append(f"{c['property']} {c['value']} (table)")
        elif c["kind"] == "equation" and (c.get("equation") or {}).get("template") in ("herschel_bulkley", "first_order_arrhenius", "arrhenius_viscosity"):
            approve(c["id"], {"material_id": mat, "review_status": "approved"})
            approved.append(c["equation"]["name"])
    log.append(f"approved {len(approved)} candidates")
    db_geo = db.get_doc("geometries", f"geo-{project_id}")
    if not db_geo:
        from .routes_workspace import _geometry_for
        _geometry_for(project_id)
    existing = {t["name"]: t for t in db.list_docs("twins") if t.get("project_id") == project_id}
    created = []
    specs = [
        ("Snack bar heating with protein denaturation", {
            "geometry_object_id": "obj-bar", "material": {"type": "formulation", "id": "baseline-pea-snack"},
            "physics": [{"kind": "heat", "enabled": True}, {"kind": "kinetics", "enabled": True}],
            "conditions": {"initial_temperature": 20.0, "concentration": None},
            "boundaries": {"default": {"type": "convection", "h": 25.0, "T_inf": 120.0}, "z-": {"type": "convection", "h": 60.0, "T_inf": 120.0}},
            "kinetics": {"material_id": mat, "initial_native_fraction": 1.0},
            "study": {"type": "time", "t_end": 1200.0, "dt": 10.0, "frames": 30, "sweep": {"parameter": "boundary_h", "values": [10, 25, 50, 100]}, "sensitivity": {"delta": 0.1}}}),
        ("Extrusion die flow — PPI 15 % w/w, 25 °C", {
            "geometry_object_id": "obj-die", "material": {"type": "material", "id": mat}, "physics": [{"kind": "flow", "enabled": True}],
            "conditions": {"initial_temperature": 25.0, "concentration": 15.0}, "flow": {"flow_rate_ml_min": 20.0, "temperature": 25.0},
            "study": {"type": "stationary", "t_end": 1.0, "dt": 1.0, "frames": 2, "sweep": {"parameter": "boundary_h", "values": [10]}, "sensitivity": {"delta": 0.1}}}),
    ]
    studies = []
    for name, spec in specs:
        t = existing.get(name)
        if not t:
            t = twins.default_twin(project_id, name)
            t.update(spec)
            t["id"] = f"twin-{abs(hash(name)) % 10**8:08d}"
            t["notes"] = NOTE
            t = db.put_doc("twins", t)
            created.append(t["id"])
        s = twins.run_study(t)
        s["notes"] = NOTE
        db.put_doc("studies", s)
        studies.append({"twin": t["name"], "study": s["id"], "warnings": s["warnings"]})
    return {"paper_id": paper["id"], "approved": approved, "twins_created": created, "studies": studies, "log": log, "note": NOTE}
