"""REST endpoints for research papers (PDF import, preview, metadata)."""
from __future__ import annotations

from fastapi import APIRouter, Body, File, Form, HTTPException, UploadFile
from fastapi.responses import FileResponse, Response

from . import db, papers, sample_docs

router = APIRouter(prefix="/api")
MAX_PDF_BYTES = 80 * 1024 * 1024


def _paper(pid: str) -> dict:
    p = db.get_doc("papers", pid)
    if not p:
        raise HTTPException(404, "paper not found")
    return p


@router.get("/papers")
def list_papers(library_id: str | None = None):
    out = []
    exts = db.list_docs("extractions")
    for p in db.list_docs("papers"):
        if library_id and library_id not in p.get("library_ids", []):
            continue
        s = papers.summary(p)
        mine = [e for e in exts if e.get("parent_id") == p["id"]]
        s["extraction_counts"] = {k: sum(1 for e in mine if e.get("status") == k) for k in ("pending", "approved", "rejected")}
        out.append(s)
    return sorted(out, key=lambda p: p.get("imported_at", ""), reverse=True)


@router.post("/papers")
async def upload_paper(file: UploadFile = File(...), library_ids: str = Form("")):
    content = await file.read()
    if len(content) > MAX_PDF_BYTES:
        raise HTTPException(413, "PDF larger than 80 MB")
    libs = [x for x in library_ids.split(",") if x]
    p = papers.import_pdf(content, file.filename or "paper.pdf", libs)
    return papers.summary(p)


@router.post("/papers/sample")
def import_sample():
    p = papers.import_pdf(sample_docs.build_sample_pdf(), "synthetic_test_document_pea_protein.pdf", ["lib-plant-protein", "lib-rheology"])
    p = db.get_doc("papers", p["id"])
    p["synthetic_test_document"] = True
    p["metadata"]["note"] = "SYNTHETIC TEST DOCUMENT generated by Synthea Simulation; values are invented for software testing."
    db.put_doc("papers", p)
    return papers.summary(p)


@router.get("/papers/{pid}")
def get_paper(pid: str):
    return _paper(pid)


@router.put("/papers/{pid}")
def update_paper(pid: str, body: dict = Body(...)):
    p = _paper(pid)
    if "metadata" in body:
        meta = {**p.get("metadata", {}), **body["metadata"]}
        meta["citation"] = body["metadata"].get("citation") or papers.citation(meta)
        p["metadata"] = meta
    if "library_ids" in body:
        p["library_ids"] = body["library_ids"]
    return papers.summary(db.put_doc("papers", p))


@router.delete("/papers/{pid}")
def delete_paper(pid: str):
    p = _paper(pid)
    used = [r for r in db.list_docs("properties") if (r.get("source") or {}).get("paper_id") == pid and r.get("review_status") in ("approved", "reviewed")]
    used += [m for m in db.list_docs("sci_models") if (m.get("source") or {}).get("paper_id") == pid and m.get("status") not in ("extracted", "rejected")]
    if used:
        raise HTTPException(409, f"{len(used)} reviewed/approved records cite this paper; it cannot be deleted (traceability). Deprecate those records first.")
    for e in db.list_children("extractions", pid):
        db.delete_doc("extractions", e["id"])
    path = papers.pdf_path(p)
    if path:
        import os
        os.remove(path)
    db.delete_doc("papers", pid)
    return {"deleted": pid}


@router.get("/papers/{pid}/file")
def paper_file(pid: str):
    path = papers.pdf_path(_paper(pid))
    if not path:
        raise HTTPException(404, "original PDF not available on this machine")
    return FileResponse(path, media_type="application/pdf")


@router.get("/papers/{pid}/page/{n}.png")
def page_png(pid: str, n: int, zoom: float = 1.5):
    try:
        return Response(papers.render_page(_paper(pid), n, max(0.5, min(zoom, 4.0))), media_type="image/png", headers={"Cache-Control": "max-age=3600"})
    except FileNotFoundError as e:
        raise HTTPException(404, str(e))


@router.get("/papers/{pid}/search")
def search(pid: str, page: int, q: str):
    return {"rects": papers.search(_paper(pid), page, q)}
